#requires -version 5.1
<#
.SYNOPSIS
  Windows desktop-pet shell for the DeepSeek Harness plugin.

.DESCRIPTION
  Compiles DesktopPet.cs with the in-box Windows PowerShell 5.1 C# compiler and
  runs it as an STA WPF application. The process is intentionally a separate
  OS process: DSH client plugins run inside the browser sandbox and cannot
  create transparent, always-on-top native windows.

  This script only starts the UI. It never deletes user files. The C# shell
  delegates every drop to IFileOperation with FOFX_RECYCLEONDELETE, which
  recycles the item or fails without falling back to a permanent delete.

.PARAMETER ConfigPath
  Absolute path to the JSON config written by the DSH host plugin.

.PARAMETER Port
  Loopback TCP port of the host bridge.

.PARAMETER Token
  One-time handshake token generated by the host.

.PARAMETER Demo
  Run a self-contained UI demo without a host connection.

.PARAMETER SourcePath
  Optional path to DesktopPet.cs (defaults to the file beside this script).
#>
[CmdletBinding()]
param(
    [string]$ConfigPath = '',
    [int]$Port = 0,
    [string]$Token = '',
    [switch]$Demo,
    [string]$SourcePath = '',
    [string]$DataDir = ''
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Console]::InputEncoding = [Text.UTF8Encoding]::new($false)
[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
if ([string]::IsNullOrWhiteSpace($SourcePath)) { $SourcePath = Join-Path $scriptDir 'DesktopPet.cs' }

# The host passes a writable data directory (normally under $DSH_HOME).  A
# local test can pass the same switch; without either, fall back to the user's
# local app data.
if ([string]::IsNullOrWhiteSpace($DataDir)) { $DataDir = $env:DSH_PET_DATA_DIR }
if ([string]::IsNullOrWhiteSpace($DataDir)) { $DataDir = Join-Path $env:LOCALAPPDATA 'DshDesktopPet' }
$env:DSH_PET_DATA_DIR = $DataDir

$logDir = $DataDir
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$logPath = Join-Path $logDir 'launcher.log'

function Write-LauncherLog([string]$Level, [string]$Message) {
    try {
        $line = '{0} [{1}] {2}' -f (Get-Date).ToString('yyyy-MM-dd HH:mm:ss.fff'), $Level, $Message
        Add-Content -LiteralPath $logPath -Value $line -Encoding UTF8
    } catch { }
}

try {
    if (-not (Test-Path -LiteralPath $SourcePath -PathType Leaf)) {
        throw "DesktopPet.cs not found: $SourcePath"
    }

    # Windows PowerShell 5.1 compiles with the .NET Framework C# 5 compiler.
    # Full paths are required here: Add-Type does not reliably resolve WPF
    # assemblies by simple name from the GAC on every Windows installation.
    $framework = [Runtime.InteropServices.RuntimeEnvironment]::GetRuntimeDirectory().TrimEnd('\')
    $references = @(
        (Join-Path $framework 'System.dll'),
        (Join-Path $framework 'System.Core.dll'),
        (Join-Path $framework 'System.Xml.dll'),
        (Join-Path $framework 'System.Web.Extensions.dll'),
        (Join-Path $framework 'System.Xaml.dll'),
        (Join-Path $framework 'System.Windows.Forms.dll'),
        (Join-Path $framework 'System.Drawing.dll'),
        (Join-Path $framework 'WPF\WindowsBase.dll'),
        (Join-Path $framework 'WPF\PresentationCore.dll'),
        (Join-Path $framework 'WPF\PresentationFramework.dll')
    )

    $already = 'DshDesktopPet.Program' -as [type]
    if (-not $already) {
        Write-LauncherLog 'INFO' "compiling $SourcePath"
        Add-Type -Path $SourcePath -ReferencedAssemblies $references -ErrorAction Stop
    }

    $argv = @()
    if ($ConfigPath) { $argv += @('-ConfigPath', $ConfigPath) }
    if ($Port -gt 0) { $argv += @('-Port', $Port.ToString([Globalization.CultureInfo]::InvariantCulture)) }
    if ($Token) { $argv += @('-Token', $Token) }
    if ($Demo) { $argv += '-Demo' }

    Write-LauncherLog 'INFO' 'starting WPF shell'
    [DshDesktopPet.Program]::Main([string[]]$argv)
}
catch {
    $message = $_.Exception.ToString()
    Write-LauncherLog 'ERROR' $message
    try {
        Add-Type -AssemblyName PresentationFramework -ErrorAction SilentlyContinue
        [System.Windows.MessageBox]::Show(
            "妗屽疇鍚姩澶辫触銆俙n`n$($_.Exception.Message)`n`n鏃ュ織锛?logPath",
            'DSH Desktop Pet',
            'OK',
            'Error') | Out-Null
    } catch { }
    exit 1
}
